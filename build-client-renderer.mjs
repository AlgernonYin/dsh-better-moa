/* Bundle the tested, dependency-free renderer into an official lazy Client chunk. */
import { readFile, writeFile } from 'node:fs/promises'
const source = await readFile(new URL('./advice-renderer.js', import.meta.url), 'utf8')
const names = [...source.matchAll(/^export (?:async )?(?:function|const) ([A-Za-z_$][\w$]*)/gm)].map(match => match[1])
if (!names.includes('createAdviceNodeDefinition') || !names.includes('registerAdviceRenderer')) {
  throw new Error('advice-renderer.js is missing its public renderer contract')
}
const body = source.replace(/^export /gm, '')
const chunk = `/* Generated by build-client-renderer.mjs. Do not edit separately. */\nwindow.__ModuleLoader__.load({\n  id: 'dsh-better-moa', chunk: 'client.advice-renderer.js',\n  factory() {\n${body}\nreturn { ${names.join(', ')} }\n  },\n})\n`
if (process.argv.includes('--check')) {
  const current = await readFile(new URL('./client.advice-renderer.js', import.meta.url), 'utf8').catch(() => '')
  if (current !== chunk) throw new Error('client.advice-renderer.js is stale; run node build-client-renderer.mjs')
  console.log('advice renderer chunk: up to date')
} else {
  await writeFile(new URL('./client.advice-renderer.js', import.meta.url), chunk, 'utf8')
  console.log(`advice renderer chunk: ${names.length} exports`)
}
